export const getProjectByPath = (
  path: string[],
): ProjectDetails | null => {
  if (path.length !== 2 || path[0] !== 'projects') {
    return null
  }

  return projectsBySlug[path[1]] ?? null
}

export const getAllProjects = (): ProjectDetails[] =>
  Object.values(projectsBySlug)
